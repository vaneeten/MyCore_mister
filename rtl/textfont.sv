task drawchar;
	input [11:0]		xpos;
	input [11:0]		ypos;
	input [6:0]			ascii;
	input [11:0]		fb_width;
	input [11:0]		fb_height;
	input [13:0]		fb_stride;
	input [7:0]			r,g,b;
	input [2:0]			i;			// 0..7
	input [3:0]			j;			// 0..15

	output reg [63:0]	pixel64;
	output reg [31:0]	fb_offs;
	output [7:0]		fb_be;
	    
	reg [11:0] 			x, y;
    reg [31:0] 			raw_offs;
	reg [127:0] 		character;
	reg [7:0]			row;
	reg					pixel;

	begin
		character = font_8x16_src128[ascii];
		row = character[j*8 +: 8];
		pixel = row[i];
		x = xpos + {9'd0,i};
		y = ypos - {8'd0,j};
		if (x < fb_width && y < fb_height)
		begin
			raw_offs = ({20'd0, y} * {18'd0, fb_stride}) + ({20'd0, x} << 2);
			pixel64 <= {8'hff, b, g, r, 8'hff, b, g, r};
			fb_be   <= (!pixel)? 8'h00 : raw_offs[2] ? 8'b1111_0000 : 8'b0000_1111;
   			fb_offs <= {raw_offs[31:3], 3'b000};
		end
        else begin
            fb_be <= 8'h00;
        end
	end
endtask

